"""Android launcher icons from icon.svg / icon.png (see mkicon.py for where those come from).
Writes, under android/app/src/main/res:
  drawable/ic_launcher_background.xml   the purple-blue gradient, as a vector
  drawable/ic_launcher_foreground.xml   the mark from icon.svg, as a vector (also the Android 13+ themed icon)
  mipmap-anydpi-v26/ic_launcher*.xml    the adaptive icon (Android 8+)
  mipmap-*/ic_launcher*.png             resized icon.png for Android 7 (needs Pillow)
Regenerate: python3 build/mkicon_android.py"""
import os, re
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, '..', 'android', 'app', 'src', 'main', 'res')
svg = open(os.path.join(HERE, 'icon.svg')).read()

paths = re.findall(r'<path d="([^"]+)"', svg)
width = float(re.search(r'stroke-width="([\d.]+)"', svg).group(1))
stops = re.search(r'id="bg".*?stop-color="(#\w+)".*?stop-color="(#\w+)"', svg).group(1, 2)

# The mark is 620 units wide in the 1024 tile; on the 108dp adaptive canvas it gets 48dp, well inside the 66dp safe circle.
MARK = 48
s = MARK / 620
t = 54 - 512 * s

def write(rel, text):
    """Write `text` to `rel` under the Android res folder, creating folders as needed."""
    f = os.path.join(RES, rel); os.makedirs(os.path.dirname(f), exist_ok=True)
    open(f, 'w').write(text)

write('drawable/ic_launcher_background.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by build/mkicon_android.py from build/icon.svg -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108">
                <item android:offset="0" android:color="{stops[0]}"/>
                <item android:offset="1" android:color="{stops[1]}"/>
            </gradient>
        </aapt:attr>
    </path>
</vector>
''')

strokes = ''.join(f'''
        <path android:pathData="{d}" android:strokeColor="#FFFFFF" android:strokeWidth="{width}"
            android:strokeLineCap="round" android:strokeLineJoin="round"/>''' for d in paths)
write('drawable/ic_launcher_foreground.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by build/mkicon_android.py from build/icon.svg -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:scaleX="{s:.6f}" android:scaleY="{s:.6f}" android:translateX="{t:.4f}" android:translateY="{t:.4f}">{strokes}
    </group>
</vector>
''')

adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by build/mkicon_android.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
'''
write('mipmap-anydpi-v26/ic_launcher.xml', adaptive)
write('mipmap-anydpi-v26/ic_launcher_round.xml', adaptive)

# Android 7 has no adaptive icons: the square icon as is, and a round one cut from the tile's middle.
src = Image.open(os.path.join(HERE, 'icon.png')).convert('RGBA')
tile = src.crop((32, 32, 992, 992))
mask = Image.new('L', tile.size, 0); ImageDraw.Draw(mask).ellipse((0, 0) + tile.size, fill=255)
round_ = Image.new('RGBA', tile.size, (0, 0, 0, 0)); round_.paste(tile, (0, 0), mask)
for dpi, px in {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}.items():
    os.makedirs(os.path.join(RES, f'mipmap-{dpi}'), exist_ok=True)
    src.resize((px, px), Image.LANCZOS).save(os.path.join(RES, f'mipmap-{dpi}', 'ic_launcher.png'), optimize=True)
    round_.resize((px, px), Image.LANCZOS).save(os.path.join(RES, f'mipmap-{dpi}', 'ic_launcher_round.png'), optimize=True)
print('Android icons written to', os.path.normpath(RES))
